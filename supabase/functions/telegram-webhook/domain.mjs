export function requiredConfiguration(env) {
  const token = env.TELEGRAM_BOT_TOKEN?.trim() ?? "";
  const webhookSecret = env.TELEGRAM_WEBHOOK_SECRET?.trim() ?? "";
  const databaseUrl = env.DATABASE_URL?.trim() ?? "";
  let phoneKey;
  try {
    phoneKey = decodePhoneIdentityKey(env.PHONE_IDENTITY_HMAC_KEY ?? "");
  } catch {
    phoneKey = null;
  }
  let databaseUrlIsTransactionPooled = false;
  try {
    const parsed = new URL(databaseUrl);
    databaseUrlIsTransactionPooled = ["postgres:", "postgresql:"].includes(parsed.protocol)
      && parsed.hostname.length > 0 && parsed.username.length > 0 && parsed.password.length > 0
      && parsed.port === "6543";
  } catch {
    databaseUrlIsTransactionPooled = false;
  }
  return {
    ok: Boolean(token && databaseUrlIsTransactionPooled && phoneKey),
    token,
    webhookSecret,
    databaseUrl,
    phoneKey,
    webhookConfigured: /^[A-Za-z0-9_-]{1,256}$/.test(webhookSecret),
  };
}
