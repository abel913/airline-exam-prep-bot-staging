export function message(language, key, ...args) {
  const text = (language === "am" ? AM : EN)[key] ?? EN[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (_match, index) => String(args[Number(index)] ?? ""));
}

export function normalizeEthiopianPhone(input) {
  if (typeof input !== "string" || input.length > 32 || !/^[+0-9 ()-]+$/.test(input)) {
    throw new TypeError("INVALID_ETHIOPIAN_PHONE");
  }
  const digits = input.replace(/[ ()-]/g, "");
  if (/^0[79][0-9]{8}$/.test(digits)) return `+251${digits.slice(1)}`;
  if (/^251[79][0-9]{8}$/.test(digits)) return `+${digits}`;
  if (/^\+251[79][0-9]{8}$/.test(digits)) return digits;
  throw new TypeError("INVALID_ETHIOPIAN_PHONE");
}

export function decodePhoneIdentityKey(base64) {
  if (typeof base64 !== "string" || !/^[A-Za-z0-9+/]+={0,2}$/.test(base64)) {
    throw new TypeError("PHONE_IDENTITY_NOT_CONFIGURED");
  }
  let binary;
  try {
    binary = atob(base64);
  } catch {
    throw new TypeError("PHONE_IDENTITY_NOT_CONFIGURED");
  }
  const bytes = Uint8Array.from(binary, (character) => character.charCodeAt(0));
  if (bytes.length < 32) throw new TypeError("PHONE_IDENTITY_NOT_CONFIGURED");
  return bytes;
}

export async function hmacSha256Hex(keyBytes, text) {
  const key = await crypto.subtle.importKey("raw", keyBytes, { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const digest = new Uint8Array(await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(text)));
  return Array.from(digest, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

export async function phoneIdentity(keyBytes, canonicalPhone) {
  return hmacSha256Hex(keyBytes, `phone:${canonicalPhone}`);
}

export async function phoneKeyFingerprint(keyBytes) {
  return hmacSha256Hex(keyBytes, "airline-exam-phone-key-v1");
}

export function constantTimeTextEqual(expected, supplied) {
  const a = new TextEncoder().encode(expected);
  const b = new TextEncoder().encode(supplied);
  let difference = a.length ^ b.length;
  const size = Math.max(a.length, b.length);
  for (let index = 0; index < size; index += 1) {
    difference |= (a[index] ?? 0) ^ (b[index] ?? 0);
  }
  return difference === 0;
}

